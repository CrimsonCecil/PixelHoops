CREATE TABLE IF NOT EXISTS profiles (id TEXT PRIMARY KEY, name TEXT NOT NULL, data TEXT NOT NULL, updated REAL NOT NULL);
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT);
CREATE TABLE IF NOT EXISTS history (id TEXT, name TEXT, data TEXT, updated REAL, op TEXT);
CREATE TABLE IF NOT EXISTS replays (id TEXT PRIMARY KEY, name TEXT UNIQUE NOT NULL, meta TEXT, size INT, created REAL);
CREATE TABLE IF NOT EXISTS replay_chunks (id TEXT, seq INT, data TEXT, PRIMARY KEY(id,seq));
CREATE TABLE IF NOT EXISTS rooms (code TEXT PRIMARY KEY, token TEXT NOT NULL, name TEXT NOT NULL, mode TEXT NOT NULL, players INTEGER NOT NULL, capacity INTEGER NOT NULL, updated REAL NOT NULL);
