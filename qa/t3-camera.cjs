const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ctx = vm.createContext({});
ctx.window = ctx;
for (const file of ['tune', 'render']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/' + file + '.js'), 'utf8'), ctx);
const { TUNE: T, render: R, CAM3 } = ctx.PH;
assert.deepEqual(JSON.parse(JSON.stringify(T.over())), {});
assert.deepEqual(CAM3.map(c => T.get(c.k)).join(','), '1,8.2,10.8,0.55,4.5,0.54');
R.setCamTuned({ height: 10, zoom: 0.8 }, 't3');
assert.equal(T.get('t3_camHeight'), 10);
assert.equal(T.get('t3_camZoom'), 0.8);
assert.equal(T.get('camHeight'), R.CAM_DEF.height);
R.setCamTuned({}, 't3');
R.setCamTuned({ unknown: 3 }, 't3');
assert.equal(Object.keys(T.over()).length, 2);
T.load({ t3_camHeight: 9.5 });
assert.equal(T.get('t3_camHeight'), 9.5);
R.resetCamTuned('t3');
assert.equal(T.get('t3_camHeight'), 8.2);
assert.deepEqual(JSON.parse(JSON.stringify(T.over())), {});
console.log('PASS: 3V3 camera defaults, panel writes, empty/unknown writes, profile load and reset stay isolated from 1V1.');
